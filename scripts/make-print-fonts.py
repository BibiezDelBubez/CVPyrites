#!/usr/bin/env python3
"""
Static font instances for the PDF ("Save as PDF").

Chrome embeds variable fonts in a PDF as Type 3 fonts, which some ATS (resume
parsers) read poorly. This script turns every variable @font-face in
src/styles/fonts.css into a static file for that exact weight, so the printed PDF
embeds ordinary TrueType fonts instead.

Output:
  public/fonts/print/*.woff2     one static file per variable face
  src/styles/fonts-print.css     @font-face rules for "<Family> Print"

The print stack is "<Family> Print", "<Family>", fallback (see fontStack in
src/data/fonts.ts): if a static file is missing (e.g. offline), the browser
falls back to the variable font, which has the same metrics, so the layout
never changes. Only the print page loads fonts-print.css.

Run after scripts/fetch-fonts.cjs whenever the font list changes:
  pip install fonttools brotli
  python3 scripts/make-print-fonts.py
"""
import os
import re
import sys

from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC_CSS = os.path.join(ROOT, 'src', 'styles', 'fonts.css')
OUT_CSS = os.path.join(ROOT, 'src', 'styles', 'fonts-print.css')
FONT_DIR = os.path.join(ROOT, 'public', 'fonts')
OUT_DIR = os.path.join(FONT_DIR, 'print')


def prop(block, name):
    m = re.search(name + r'\s*:\s*([^;]+);', block)
    return m.group(1).strip() if m else None


def main():
    css = open(SRC_CSS, encoding='utf-8').read()
    os.makedirs(OUT_DIR, exist_ok=True)
    rules, made, cache = [], 0, {}
    for block in re.findall(r'@font-face\s*{[^}]*}', css):
        family = prop(block, 'font-family').strip('\'"')
        style = prop(block, 'font-style') or 'normal'
        weight = prop(block, 'font-weight') or '400'
        rng = prop(block, 'unicode-range')
        url = re.search(r'url\(/fonts/([^)]+)\)', block).group(1)
        src = os.path.join(FONT_DIR, url)
        if url not in cache:
            cache[url] = 'fvar' in TTFont(src)
        if not cache[url]:
            continue  # already static: Chrome embeds it as TrueType
        wght = int(weight.split()[0])
        name = f"{os.path.splitext(url)[0]}-{wght}{'i' if style == 'italic' else ''}.woff2"
        out = os.path.join(OUT_DIR, name)
        if not os.path.exists(out):
            font = TTFont(src)
            limits = {a.axisTag: a.defaultValue for a in font['fvar'].axes}
            limits['wght'] = max(min(wght, next(a.maxValue for a in font['fvar'].axes if a.axisTag == 'wght')),
                                 next(a.minValue for a in font['fvar'].axes if a.axisTag == 'wght'))
            static = instancer.instantiateVariableFont(font, limits)
            static.flavor = 'woff2'
            static.save(out)
            made += 1
        rules.append(
            '@font-face {\n'
            f"  font-family: '{family} Print';\n"
            f'  font-style: {style};\n'
            f'  font-weight: {wght};\n'
            '  font-display: block;\n'
            f'  src: url(/fonts/print/{name}) format(\'woff2\');\n'
            + (f'  unicode-range: {rng};\n' if rng else '')
            + '}'
        )
    head = ('/* GENERATED by scripts/make-print-fonts.py — do not edit by hand.\n'
            '   Static instances of the variable fonts, used only by the print page so\n'
            '   the PDF embeds TrueType fonts instead of Type 3 (better for ATS). */\n\n')
    open(OUT_CSS, 'w', encoding='utf-8', newline='\n').write(head + '\n'.join(rules) + '\n')
    print(f'{len(rules)} @font-face rules, {made} new static files in public/fonts/print/')


if __name__ == '__main__':
    sys.exit(main())
